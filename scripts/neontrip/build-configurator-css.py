#!/usr/bin/env python3
"""Build initial styles from the existing HTML and preserve the full CSS cascade.

Run after editing HTML or any listed stylesheet. --check detects stale output.
Dependencies: python3 -m pip install -r scripts/neontrip/requirements-configurator-css.txt
Product entries use the same generated startup styles as the main configurator.
Use locked npm dependencies for CSS minification. Run the runtime builder afterward.
"""
import argparse
import hashlib
import os
from pathlib import Path
import re
import subprocess

ROOT = Path(os.environ['NEONTRIP_CONFIGURATOR_ROOT']).resolve() if os.environ.get('NEONTRIP_CONFIGURATOR_ROOT') else Path(__file__).resolve().parents[2] / 'deploy' / 'configurator'
GROUPS = {
    'startup-base': ['../shared/tokens.css', '../shared/base.css', '../shared/ui.css',
                     'assets/fonts.css', 'configurator.css', 'workspace.css',
                     'site-chrome.css', 'hero.css', 'workbench.css',
                     'content-sections.css', 'delivery-calendar.css', 'content-experience.css'],
    'startup-theme': ['content-v2.css', 'lichtbuehne.css'],
    'startup-studio': ['pricing.css', 'usability.css', 'share.css', 'lichtbuehne-v4.css',
                       'designstudio.css', 'font-filters.css', 'cart-brand.css',
                       'trust-signals.css', 'section-polish.css'],
}

def minify_css(css):
    return subprocess.run(['node', str(Path(__file__).with_name('build-configurator-runtime.cjs')), '--minify-css'],
                          input=css, text=True, capture_output=True, check=True).stdout.strip()

def inline_entry_styles(html):
    # These small sheets are required at first paint. Keep their original cascade
    # positions, without making the whole page wait for two additional requests.
    for name in ['entry-room', 'design-email']:
        style = f'<style id="configurator-{name}-styles">' + minify_css((ROOT / (name + '.css')).read_text()) + '</style>'
        pattern = r'<link rel="stylesheet" href="' + re.escape(name) + r'\.css\?v=[^"]+">|<style id="configurator-' + re.escape(name) + r'-styles">.*?</style>'
        html, count = re.subn(pattern, lambda _: style, html, flags=re.S)
        if count != 1:
            raise ValueError(f'{name}: expected one entry stylesheet, got {count}')
    return html

def bundle(paths):
    parts = ['/* Generated by scripts/neontrip/build-configurator-css.py; edit source stylesheets. */\n']
    for source in paths:
        path = ROOT / source
        css = path.read_text()
        if re.search(r'@(import|charset)\b', css):
            raise ValueError(f'{source}: imports/charsets require explicit handling')
        def rebase(match):
            url = match[1].strip().strip('\"\'')
            if url.startswith(('/', '#', 'data:')) or re.match(r'[a-z]+:', url, re.I):
                return match[0]
            relative = os.path.relpath(path.parent / url, ROOT).replace(os.sep, '/')
            return f'url("{relative}")'
        parts.append(f'\n/* Source: {source} */\n' + re.sub(r'url\(([^)]+)\)', rebase, css) + '\n')
    return ''.join(parts).rstrip() + '\n'

# Critical rules are selected from the actual initial HTML, not a second hand-written layout.
# Full styles retain their source order and must load before the editor becomes interactive.
def critical_css(html, css):
    import tinycss2
    import cssselect2
    from html.parser import HTMLParser
    from xml.etree.ElementTree import Element, SubElement
    class Tree(HTMLParser):
        def __init__(self):
            super().__init__(); self.root = Element('document'); self.stack = [self.root]
        def handle_starttag(self, tag, attrs):
            node = SubElement(self.stack[-1], tag, dict((k, v or '') for k, v in attrs))
            if tag not in {'area','base','br','col','embed','hr','img','input','link','meta','param','source','track','wbr'}:
                self.stack.append(node)
        def handle_endtag(self, tag):
            for index in range(len(self.stack)-1, 0, -1):
                if self.stack[index].tag == tag:
                    del self.stack[index:]; break
    tree = Tree(); tree.feed(html)
    root = cssselect2.ElementWrapper.from_html_root(tree.root.find('html'))
    elements = [node for node in root.iter_subtree() if not any(('hidden' in parent.etree_element.attrib and parent.etree_element.get('role') == 'tabpanel') or parent.etree_element.tag == 'dialog' for parent in (*node.ancestors, node)) and (node.etree_element.tag in {'html','body'} or 'skip' in node.classes or
                any(parent.etree_element.get('id') == 'main' or 'config-site-header' in parent.classes
                    for parent in (*node.ancestors, node)))]
    def select(rules):
        output = []
        for rule in rules:
            if rule.type == 'qualified-rule':
                # A matching selector must not pull every unrelated selector in
                # a comma group into the first-paint sheet. Commas inside :is()
                # and other functions stay inside their parsed component value.
                groups = [[]]
                for token in rule.prelude:
                    if token.type == 'literal' and token.value == ',': groups.append([])
                    else: groups[-1].append(token)
                kept = []
                for tokens in groups:
                    selector = tinycss2.serialize(tokens).strip()
                    try:
                        tests = cssselect2.compile_selector_list(selector)
                        keep = '[hidden]' in selector or any(test.test(node) for test in tests for node in elements)
                    except cssselect2.SelectorError:
                        keep = True  # Keep unknown syntax conservatively.
                    if keep: kept.append(selector)
                if kept: output.append(','.join(kept) + '{' + tinycss2.serialize(rule.content).strip() + '}')
            elif rule.type == 'at-rule':
                prefix = '@' + rule.at_keyword + ' ' + tinycss2.serialize(rule.prelude).strip()
                if rule.content is None: output.append(prefix + ';')
                elif rule.lower_at_keyword in {'media','supports','layer','container'}:
                    nested = select(tinycss2.parse_rule_list(rule.content, skip_comments=True, skip_whitespace=True))
                    if nested: output.append(prefix + '{' + nested + '}')
                else: output.append(prefix + '{' + tinycss2.serialize(rule.content).strip() + '}')
        return '\n'.join(output)
    return select(tinycss2.parse_stylesheet(css, skip_comments=True, skip_whitespace=True))

def critical_media_sizes():
    # Intrinsic sizes also matter below the fold: an unstyled SVG can otherwise
    # paint across the viewport before its asynchronously loaded section sheet.
    import tinycss2
    output = []
    def visit(rules):
        for rule in rules:
            if rule.type == 'qualified-rule':
                selector = tinycss2.serialize(rule.prelude)
                if 'svg' in selector:
                    declarations = [item for item in tinycss2.parse_declaration_list(rule.content, skip_comments=True, skip_whitespace=True)
                                    if item.type == 'declaration' and item.lower_name in {'width','height','max-width','max-height'}]
                    if declarations: output.append(selector + '{' + tinycss2.serialize(declarations) + '}')
            elif rule.type == 'at-rule' and rule.content is not None and rule.lower_at_keyword in {'media','supports'}:
                start = len(output); visit(tinycss2.parse_rule_list(rule.content, skip_comments=True, skip_whitespace=True))
                nested = output[start:]; del output[start:]
                if nested: output.append('@' + rule.at_keyword + ' ' + tinycss2.serialize(rule.prelude) + '{' + ''.join(nested) + '}')
    for sheet in ['express-section.css', 'customer-reviews.css']:
        visit(tinycss2.parse_stylesheet((ROOT / sheet).read_text(), skip_comments=True, skip_whitespace=True))
    return '\n'.join(output)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    page = ROOT / 'index.html'
    html = page.read_text()
    stale = []
    complete_css = []
    for name, sources in GROUPS.items():
        css = subprocess.run(['node', str(Path(__file__).with_name('build-configurator-runtime.cjs')), '--minify-css'], input=bundle(sources), text=True, capture_output=True, check=True).stdout
        complete_css.append(css)
        path = ROOT / (name + '.css')
        if not path.exists() or path.read_text() != css:
            stale.append(path.name)
            if not args.check:
                path.write_text(css)
        version = hashlib.sha256(css.encode()).hexdigest()[:12]
        link = f'<link rel="stylesheet" data-startup-href="{name}.css?v={version}" data-startup-styles media="print">'
        link += f'<noscript><link rel="stylesheet" href="{name}.css?v={version}"></noscript>'
        current = re.compile(r'<link rel="stylesheet" (?:href|data-startup-href)="' + re.escape(name) + r'(?:\.min)?\.css\?v=[^"]+"[^>]*>(?:<noscript><link[^>]+></noscript>)?')
        if current.search(html):
            html = current.sub(link, html)
        else:
            # Replace only contiguous startup groups. Async section sheets stay
            # in their exact original positions between the generated bundles.
            patterns = [r'<link rel="stylesheet" href="' + re.escape(src) + r'(?:\?[^\"]*)?">' for src in sources]
            group = re.compile(r'\s*'.join(patterns))
            html, count = group.subn(link, html)
            if count != 1:
                raise ValueError(f'{name}: expected one contiguous source group, got {count}')
    critical = '<style id="configurator-critical">' + minify_css(critical_css(html, '\n'.join(complete_css)) + '\n' + critical_media_sizes()) + '</style>'
    if '<style id="configurator-critical">' in html:
        html = re.sub(r'<style id="configurator-critical">.*?</style>', lambda _: critical, html, flags=re.S)
    else:
        html = html.replace('  <link rel="stylesheet" href="startup-base', critical + '\n  <link rel="stylesheet" href="startup-base', 1)
    html = inline_entry_styles(html)
    loader = '<script id="configurator-full-styles">window.neontripStylesReady=new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(async()=>{const links=[...document.querySelectorAll("link[data-startup-href]")];await Promise.all(links.map(link=>new Promise(done=>{link.onload=link.onerror=done;link.href=link.dataset.startupHref;})));for(const link of links){link.media="all";link.onload=link.onerror=null;}requestAnimationFrame(resolve);})));</script>'
    if 'id="configurator-full-styles"' in html:
        html = re.sub(r'<script id="configurator-full-styles">.*?</script>', lambda _: loader, html)
    else:
        html = html.replace('</head>', loader + '\n</head>', 1)
    if html != page.read_text():
        stale.append('index.html bundle links')
        if not args.check:
            page.write_text(html)
    for product in sorted(ROOT.glob('neon-*.html')):
        original = product.read_text()
        # Product pages already load the complete bundles directly. Preserve
        # their cascade; only remove the two additional blocking requests.
        updated = inline_entry_styles(original)
        if updated != original:
            stale.append(product.name + ' entry styles')
            if not args.check:
                product.write_text(updated)
    if args.check and stale:
        raise SystemExit('Rebuild configurator CSS: ' + ', '.join(stale))
    print('Configurator CSS ' + ('verified' if args.check else 'built') + ': initial HTML rules inline; full bundles async in original order.')

if __name__ == '__main__':
    main()
