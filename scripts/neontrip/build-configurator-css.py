#!/usr/bin/env python3
"""Bundle existing startup styles without changing cascade order or source files.

Run after editing any listed stylesheet. --check fails on a stale bundle/link.
Shopping pages retain their existing individual stylesheets.
The check also guards the matching startup module preload URLs.
"""
import argparse
import hashlib
import os
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2] / 'deploy' / 'configurator'
GROUPS = {
    'startup-base': ['../shared/tokens.css', '../shared/base.css', '../shared/ui.css',
                     'assets/fonts.css', 'configurator.css', 'workspace.css',
                     'site-chrome.css', 'hero.css', 'workbench.css',
                     'content-sections.css', 'delivery-calendar.css', 'content-experience.css'],
    'startup-theme': ['content-v2.css', 'lichtbuehne.css'],
    'startup-studio': ['pricing.css', 'usability.css', 'share.css', 'lichtbuehne-v4.css',
                       'designstudio.css', 'font-filters.css', 'cart-brand.css',
                       'trust-signals.css', 'section-polish.css'],
}

def bundle(paths):
    parts = ['/* Generated by scripts/neontrip/build-configurator-css.py; edit source stylesheets. */\n']
    for source in paths:
        path = ROOT / source
        css = path.read_text()
        if re.search(r'@(import|charset)\b', css):
            raise ValueError(f'{source}: imports/charsets require explicit handling')
        def rebase(match):
            url = match[1].strip().strip('\"\'')
            if url.startswith(('/', '#', 'data:')) or re.match(r'[a-z]+:', url, re.I):
                return match[0]
            relative = os.path.relpath(path.parent / url, ROOT).replace(os.sep, '/')
            return f'url("{relative}")'
        parts.append(f'\n/* Source: {source} */\n' + re.sub(r'url\(([^)]+)\)', rebase, css) + '\n')
    return ''.join(parts).rstrip() + '\n'

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    page = ROOT / 'index.html'
    html = page.read_text()
    imports = {url.removeprefix('./') for url in re.findall(
        r"^import .*?from ['\"](.+?)['\"]", (ROOT / 'configurator.js').read_text(), re.M)}
    preloads = set(re.findall(r'<link rel="modulepreload" href="([^"]+)"', html))
    if not imports.issubset(preloads):
        raise SystemExit('Update startup module preloads: ' + ', '.join(sorted(imports - preloads)))
    stale = []
    for name, sources in GROUPS.items():
        css = bundle(sources)
        path = ROOT / (name + '.css')
        if not path.exists() or path.read_text() != css:
            stale.append(path.name)
            if not args.check:
                path.write_text(css)
        version = hashlib.sha256(css.encode()).hexdigest()[:12]
        link = f'<link rel="stylesheet" href="{name}.css?v={version}">'
        current = re.compile(r'<link rel="stylesheet" href="' + re.escape(name) + r'\.css\?v=[^"]+">')
        if current.search(html):
            html = current.sub(link, html)
        else:
            # Replace only contiguous startup groups. Async section sheets stay
            # in their exact original positions between the generated bundles.
            patterns = [r'<link rel="stylesheet" href="' + re.escape(src) + r'(?:\?[^\"]*)?">' for src in sources]
            group = re.compile(r'\s*'.join(patterns))
            html, count = group.subn(link, html)
            if count != 1:
                raise ValueError(f'{name}: expected one contiguous source group, got {count}')
    if html != page.read_text():
        stale.append('index.html bundle links')
        if not args.check:
            page.write_text(html)
    if args.check and stale:
        raise SystemExit('Rebuild configurator CSS: ' + ', '.join(stale))
    print('Configurator CSS ' + ('verified' if args.check else 'built') + ': 23 blocking requests replaced by 3; CSS order preserved.')

if __name__ == '__main__':
    main()
