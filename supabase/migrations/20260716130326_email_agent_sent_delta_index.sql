create table if not exists public.email_agent_mail_sync_state (
  mailbox_key text primary key,
  folder_name text not null default 'sentitems',
  cursor_url text,
  cursor_kind text not null default 'initial',
  initial_since timestamptz not null default (now() - interval '14 days'),
  next_retry_at timestamptz,
  lease_owner text,
  lease_until timestamptz,
  last_attempt_at timestamptz,
  last_success_at timestamptz,
  consecutive_errors integer not null default 0,
  last_http_status integer,
  last_error_code text,
  last_error_message text,
  last_correlation_id text,
  last_execution_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint email_agent_mail_sync_state_mailbox_key_check
    check (char_length(mailbox_key) between 3 and 320),
  constraint email_agent_mail_sync_state_folder_name_check
    check (folder_name in ('sentitems')),
  constraint email_agent_mail_sync_state_cursor_kind_check
    check (cursor_kind in ('initial', 'next', 'delta')),
  constraint email_agent_mail_sync_state_consecutive_errors_check
    check (consecutive_errors between 0 and 100000)
);

create table if not exists public.email_agent_sent_index (
  id bigint generated by default as identity primary key,
  mailbox_key text not null references public.email_agent_mail_sync_state(mailbox_key) on delete cascade,
  graph_message_id text not null,
  internet_message_id text,
  conversation_id text not null,
  sent_at timestamptz not null,
  received_at timestamptz,
  subject text,
  recipient_emails text[] not null default '{}'::text[],
  response_body_text text not null default '',
  response_body_hash text,
  sync_correlation_id text not null,
  matched_source_message_id text,
  matched_feedback_id bigint references public.email_agent_feedback(id) on delete set null,
  matched_at timestamptz,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  constraint email_agent_sent_index_graph_message_id_check
    check (char_length(graph_message_id) between 1 and 2000),
  constraint email_agent_sent_index_conversation_id_check
    check (char_length(conversation_id) between 1 and 2000),
  constraint email_agent_sent_index_body_length_check
    check (char_length(response_body_text) <= 6000),
  constraint email_agent_sent_index_message_unique
    unique (mailbox_key, graph_message_id)
);

create table if not exists public.email_agent_mail_sync_runs (
  correlation_id text primary key,
  mailbox_key text not null references public.email_agent_mail_sync_state(mailbox_key) on delete cascade,
  execution_id text not null,
  status text not null,
  request_kind text not null,
  http_status integer,
  message_count integer not null default 0,
  upserted_count integer not null default 0,
  cursor_kind text,
  retry_after_seconds integer,
  error_code text,
  error_message text,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  constraint email_agent_mail_sync_runs_status_check
    check (status in ('running', 'success', 'throttled', 'error', 'reset')),
  constraint email_agent_mail_sync_runs_request_kind_check
    check (request_kind in ('initial', 'next', 'delta')),
  constraint email_agent_mail_sync_runs_cursor_kind_check
    check (cursor_kind is null or cursor_kind in ('next', 'delta')),
  constraint email_agent_mail_sync_runs_counts_check
    check (message_count >= 0 and upserted_count >= 0),
  constraint email_agent_mail_sync_runs_execution_unique
    unique (mailbox_key, execution_id)
);

create index if not exists email_agent_sent_index_unmatched_conversation_idx
