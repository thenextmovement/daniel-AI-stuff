create or replace function public.record_google_ads_upload_attempts(p_attempts jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_item jsonb;
  v_attempt_key text;
  v_source_type text;
  v_source_id uuid;
  v_status text;
  v_effective_status text;
  v_effective_source_type text;
  v_effective_source_id uuid;
  v_attempt_number integer;
  v_attempted_at timestamptz;
  v_recorded integer := 0;
  v_marked_conversions integer := 0;
  v_marked_request_leads integer := 0;
  v_row_count integer;
begin
  if jsonb_typeof(p_attempts) <> 'array' then
    raise exception 'p_attempts must be a JSON array';
  end if;

  if jsonb_array_length(p_attempts) > 2000 then
    raise exception 'p_attempts exceeds the 2000 row limit';
  end if;

  for v_item in select value from jsonb_array_elements(p_attempts)
  loop
    v_attempt_key := nullif(btrim(v_item ->> 'attemptKey'), '');
    v_source_type := nullif(btrim(v_item ->> 'sourceType'), '');
    v_status := nullif(btrim(v_item ->> 'status'), '');

    if v_attempt_key is null or length(v_attempt_key) not between 8 and 240 then
      raise exception 'invalid attemptKey';
    end if;

    if v_source_type not in ('conversion', 'request_lead') then
      raise exception 'invalid sourceType for attempt %', v_attempt_key;
    end if;

    if v_status not in ('success', 'duplicate', 'retryable', 'permanent_failure', 'request_failure') then
      raise exception 'invalid status for attempt %', v_attempt_key;
    end if;

    begin
      v_source_id := (v_item ->> 'sourceId')::uuid;
      v_attempted_at := coalesce(nullif(v_item ->> 'attemptedAt', '')::timestamptz, now());
    exception when others then
      raise exception 'invalid sourceId or attemptedAt for attempt %', v_attempt_key;
    end;

    if v_source_type = 'conversion' and not exists (
      select 1 from public.google_ads_conversions where id = v_source_id
    ) then
      raise exception 'unknown conversion source for attempt %', v_attempt_key;
    end if;

    if v_source_type = 'request_lead' and not exists (
      select 1 from public.master_requests where id = v_source_id
    ) then
      raise exception 'unknown request source for attempt %', v_attempt_key;
    end if;

    select coalesce(max(attempt_number), 0) + 1
    into v_attempt_number
    from private.google_ads_upload_attempts
    where source_type = v_source_type
      and source_id = v_source_id;

    insert into private.google_ads_upload_attempts (
      attempt_key,
      attempt_number,
      source_type,
      source_id,
      conversion_action,
      conversion_name,
      conversion_time,
      order_id,
      payload_index,
      job_id,
      status,
      error_code,
      error_message,
      retry_after,
      attempted_at
    ) values (
      v_attempt_key,
      v_attempt_number,
      v_source_type,
      v_source_id,
      nullif(btrim(v_item ->> 'conversionAction'), ''),
      nullif(btrim(v_item ->> 'conversionName'), ''),
      (v_item ->> 'conversionTime')::timestamptz,
      nullif(btrim(v_item ->> 'orderId'), ''),
      (v_item ->> 'payloadIndex')::integer,
      nullif(v_item ->> 'jobId', '')::bigint,
      v_status,
      left(nullif(btrim(v_item ->> 'errorCode'), ''), 160),
      left(
        nullif(
          regexp_replace(btrim(v_item ->> 'errorMessage'), '[A-Za-z0-9_-]{24,}', '[redacted-id]', 'g'),
          ''
        ),
        1000
      ),
      nullif(v_item ->> 'retryAfter', '')::timestamptz,
      v_attempted_at
    )
    on conflict (attempt_key) do nothing;

    get diagnostics v_row_count = row_count;
    v_recorded := v_recorded + v_row_count;

    select source_type, source_id, status
    into v_effective_source_type, v_effective_source_id, v_effective_status
    from private.google_ads_upload_attempts
    where attempt_key = v_attempt_key;

    if v_effective_source_type is distinct from v_source_type
      or v_effective_source_id is distinct from v_source_id then
      raise exception 'attemptKey already belongs to another source';
    end if;

    if v_effective_status in ('success', 'duplicate') then
      if v_source_type = 'conversion' then
        update public.google_ads_conversions
        set uploaded_to_gads = true
        where id = v_source_id
          and uploaded_to_gads = false;
        get diagnostics v_row_count = row_count;
        v_marked_conversions := v_marked_conversions + v_row_count;
      else
        update public.master_requests
        set gads_exported_at = coalesce(gads_exported_at, v_attempted_at)
        where id = v_source_id
          and gads_exported_at is null;
        get diagnostics v_row_count = row_count;
        v_marked_request_leads := v_marked_request_leads + v_row_count;
      end if;
    end if;
  end loop;

  return jsonb_build_object(
    'received', jsonb_array_length(p_attempts),
    'recorded', v_recorded,
    'marked_conversions', v_marked_conversions,
    'marked_request_leads', v_marked_request_leads
  );
end;
$function$;

revoke all on function public.record_google_ads_upload_attempts(jsonb) from public;
revoke all on function public.record_google_ads_upload_attempts(jsonb) from anon;
revoke all on function public.record_google_ads_upload_attempts(jsonb) from authenticated;
grant execute on function public.record_google_ads_upload_attempts(jsonb) to service_role;

create or replace function public.get_pending_gads_conversions()
returns table(
  conversion_id uuid,
  gclid text,
  has_gclid boolean,
  conversion_name text,
  conversion_value numeric,
  conversion_time timestamptz,
  email text,
  hashed_email text
)
language sql
stable
security definer
set search_path = ''
as $function$
  with candidates as (
    select
      gc.id as conversion_id,
      coalesce(
        nullif(btrim(gc.gclid), ''),
        nullif(btrim(mr_direct.gclid), ''),
        nullif(btrim(mr_order.gclid), '')
      ) as resolved_gclid,
      gc.conversion_name,
      gc.conversion_value,
      coalesce(gc.conversion_time, gc.exported_at) as resolved_conversion_time,
      gc.email
    from public.google_ads_conversions gc
    left join public.master_requests mr_direct
      on mr_direct.id = gc.request_id
    left join public.master_orders mo
      on mo.shopify_order_number = gc.shopify_order_number
    left join public.master_requests mr_order
      on mr_order.id = mo.request_id
    where gc.uploaded_to_gads = false
      and gc.conversion_name in ('Offline: Angebot versendet', 'Offline: Deal gewonnen')
      and not exists (
        select 1
        from private.google_ads_upload_attempts a
        where a.source_type = 'conversion'
          and a.source_id = gc.id
          and (
            a.status = 'permanent_failure'
            or (
              a.status in ('retryable', 'request_failure')
              and coalesce(a.retry_after, a.recorded_at + interval '1 hour') > now()
            )
          )
      )
  )
  select
    conversion_id,
    resolved_gclid as gclid,
    resolved_gclid is not null as has_gclid,
    conversion_name,
    conversion_value,
    resolved_conversion_time as conversion_time,
    email,
    null::text as hashed_email
  from candidates
  where resolved_gclid is not null
    and lower(resolved_gclid) not in ('test', 'undefined', 'null')
    and lower(resolved_gclid) not like 'test%'
    and lower(resolved_gclid) not like 'diagnostic-%'
    and lower(resolved_gclid) not like 'codex_%'
    and length(resolved_gclid) >= 25
    and resolved_conversion_time is not null
  order by resolved_conversion_time asc
  limit 2000;
$function$;

revoke all on function public.get_pending_gads_conversions() from public;
revoke all on function public.get_pending_gads_conversions() from anon;
revoke all on function public.get_pending_gads_conversions() from authenticated;
grant execute on function public.get_pending_gads_conversions() to service_role;

create or replace function public.get_pending_gads_request_leads(p_lookback_days integer default 14)
returns table(
  id uuid,
  request_id text,
  gclid text,
  created_at timestamptz,
  status text,
  deal_status text
)
language sql
stable
security definer
set search_path = ''
as $function$
  select
    mr.id,
    mr.request_id,
    btrim(mr.gclid) as gclid,
    mr.created_at,
    mr.status,
    mr.deal_status
  from public.master_requests mr
  where nullif(btrim(mr.gclid), '') is not null
    and lower(btrim(mr.gclid)) not in ('test', 'undefined', 'null')
    and lower(btrim(mr.gclid)) not like 'test%'
    and lower(btrim(mr.gclid)) not like 'diagnostic-%'
    and lower(btrim(mr.gclid)) not like 'codex_%'
    and length(btrim(mr.gclid)) >= 25
    and mr.gads_exported_at is null
    and mr.created_at >= now() - make_interval(days => greatest(1, least(coalesce(p_lookback_days, 14), 90)))
    and coalesce(lower(mr.status), '') not in ('won', 'lost', 'gewonnen', 'verloren')
    and coalesce(lower(mr.deal_status), '') not in ('won', 'lost', 'gewonnen', 'verloren')
    and not exists (
      select 1
      from private.google_ads_upload_attempts a
      where a.source_type = 'request_lead'
        and a.source_id = mr.id
        and (
          a.status = 'permanent_failure'
          or (
            a.status in ('retryable', 'request_failure')
            and coalesce(a.retry_after, a.recorded_at + interval '1 hour') > now()
          )
        )
    )
  order by mr.created_at asc
  limit 200;
$function$;

revoke all on function public.get_pending_gads_request_leads(integer) from public;
revoke all on function public.get_pending_gads_request_leads(integer) from anon;
revoke all on function public.get_pending_gads_request_leads(integer) from authenticated;
grant execute on function public.get_pending_gads_request_leads(integer) to service_role;

create or replace function public.gads_upload_health_metrics()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $function$
  with offline as (
    select *
    from public.google_ads_conversions
    where conversion_name in ('Offline: Angebot versendet', 'Offline: Deal gewonnen')
  ),
  offline_metrics as (
    select
      count(*) as total_rows,
      count(*) filter (where uploaded_to_gads = true) as uploaded,
      count(*) filter (where uploaded_to_gads = false) as pending,
      count(*) filter (
        where uploaded_to_gads = false
          and exported_at < now() - interval '2 hours'
      ) as stale_pending_2h,
      max(exported_at) as newest_insert,
      max(exported_at) filter (where conversion_name = 'Offline: Angebot versendet') as newest_offline_angebot
    from offline
  ),
  request_leads_pending as (
    select
      count(*) as count,
      count(*) filter (where created_at < now() - interval '2 hours') as stale_2h,
      min(created_at) as oldest_pending_created_at
    from public.get_pending_gads_request_leads(14)
  ),
  request_leads_export as (
    select max(gads_exported_at) as newest_request_lead_exported_at
    from public.master_requests
    where gads_exported_at is not null
  ),
  pending_sent_rows as (
    select * from public.get_pending_sent_conversions(7)
  ),
  pending_sent as (
    select
      count(*) as count,
      count(*) filter (where sent_at < now() - interval '2 hours') as stale_2h,
      min(sent_at) as oldest_pending_sent_at
    from pending_sent_rows
  ),
  autoreply as (
    select count(*) as count
    from public.master_requests
    where request_id like 'autoreply-%'
      and gclid is null
      and created_at >= now() - interval '24 hours'
  ),
  latest_attempts as (
    select distinct on (source_type, source_id)
      source_type,
      source_id,
      status,
      retry_after,
      recorded_at,
      job_id
    from private.google_ads_upload_attempts
    order by source_type, source_id, recorded_at desc, id desc
  ),
  attempt_metrics as (
    select
      (select count(*) from private.google_ads_upload_attempts where recorded_at >= now() - interval '24 hours') as attempts_24h,
      (select count(*) from private.google_ads_upload_attempts where recorded_at >= now() - interval '24 hours' and status = 'success') as successes_24h,
      (select count(*) from private.google_ads_upload_attempts where recorded_at >= now() - interval '24 hours' and status = 'duplicate') as duplicates_24h,
      count(*) filter (where status = 'retryable') as retryable_latest,
      count(*) filter (where status = 'retryable' and coalesce(retry_after, recorded_at + interval '1 hour') <= now()) as retryable_due,
      count(*) filter (where status = 'permanent_failure') as permanent_failures_latest,
      count(*) filter (where status = 'request_failure') as request_failures_latest,
      max(recorded_at) as last_attempt_at,
      (
        select job_id
        from private.google_ads_upload_attempts
        where job_id is not null
        order by recorded_at desc, id desc
        limit 1
      ) as last_job_id
    from latest_attempts
  )
  select jsonb_build_object(
    'total_rows', coalesce(om.total_rows, 0),
    'uploaded', coalesce(om.uploaded, 0),
    'pending', coalesce(om.pending, 0),
    'stale_pending_2h', coalesce(om.stale_pending_2h, 0),
    'newest_insert', om.newest_insert,
    'newest_insert_age_min', case when om.newest_insert is null then null else round(extract(epoch from (now() - om.newest_insert))/60)::int end,
    'newest_offline_angebot', om.newest_offline_angebot,
    'pending_sent_conversions', coalesce(ps.count, 0),
    'stale_pending_sent_conversions_2h', coalesce(ps.stale_2h, 0),
    'oldest_pending_sent_at', ps.oldest_pending_sent_at,
    'request_leads_pending', coalesce(rlp.count, 0),
    'stale_request_leads_pending_2h', coalesce(rlp.stale_2h, 0),
    'oldest_request_lead_pending_created_at', rlp.oldest_pending_created_at,
    'newest_request_lead_exported_at', rle.newest_request_lead_exported_at,
    'newest_request_lead_export_age_min', case when rle.newest_request_lead_exported_at is null then null else round(extract(epoch from (now() - rle.newest_request_lead_exported_at))/60)::int end,
    'newest_activity_at', greatest(om.newest_insert, rle.newest_request_lead_exported_at, am.last_attempt_at),
    'newest_activity_age_min', case when greatest(om.newest_insert, rle.newest_request_lead_exported_at, am.last_attempt_at) is null then null else round(extract(epoch from (now() - greatest(om.newest_insert, rle.newest_request_lead_exported_at, am.last_attempt_at)))/60)::int end,
    'autoreply_without_gclid', coalesce(ar.count, 0),
    'receipt_attempts_24h', coalesce(am.attempts_24h, 0),
    'receipt_successes_24h', coalesce(am.successes_24h, 0),
    'receipt_duplicates_24h', coalesce(am.duplicates_24h, 0),
    'receipt_retryable_latest', coalesce(am.retryable_latest, 0),
    'receipt_retryable_due', coalesce(am.retryable_due, 0),
    'receipt_permanent_failures_latest', coalesce(am.permanent_failures_latest, 0),
    'receipt_request_failures_latest', coalesce(am.request_failures_latest, 0),
    'last_upload_attempt_at', am.last_attempt_at,
    'last_upload_job_id', am.last_job_id,
    'checked_at', now()
  )
  from offline_metrics om
  cross join pending_sent ps
  cross join request_leads_pending rlp
  cross join request_leads_export rle
  cross join autoreply ar
  cross join attempt_metrics am;
$function$;

