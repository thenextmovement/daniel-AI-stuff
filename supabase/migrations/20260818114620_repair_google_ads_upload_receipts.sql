create table private.google_ads_upload_attempts (
  id bigint generated by default as identity primary key,
  attempt_key text not null unique,
  attempt_number integer not null,
  source_type text not null,
  source_id uuid not null,
  conversion_action text not null,
  conversion_name text not null,
  conversion_time timestamptz not null,
  order_id text,
  payload_index integer not null,
  job_id bigint,
  status text not null,
  error_code text,
  error_message text,
  retry_after timestamptz,
  attempted_at timestamptz not null,
  recorded_at timestamptz not null default now(),
  constraint google_ads_upload_attempts_attempt_key_length
    check (length(attempt_key) between 8 and 240),
  constraint google_ads_upload_attempts_source_type
    check (source_type in ('conversion', 'request_lead')),
  constraint google_ads_upload_attempts_payload_index
    check (payload_index between 0 and 1999),
  constraint google_ads_upload_attempts_status
    check (status in ('success', 'duplicate', 'retryable', 'permanent_failure', 'request_failure')),
  constraint google_ads_upload_attempts_attempt_number
    check (attempt_number > 0)
);

create index google_ads_upload_attempts_source_recorded_idx
  on private.google_ads_upload_attempts (source_type, source_id, recorded_at desc, id desc);

create index google_ads_upload_attempts_job_idx
  on private.google_ads_upload_attempts (job_id)
  where job_id is not null;

create index google_ads_upload_attempts_unresolved_idx
  on private.google_ads_upload_attempts (status, retry_after, recorded_at)
  where status in ('retryable', 'permanent_failure', 'request_failure');

